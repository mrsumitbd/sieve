# ── Overview ──────────────────────────────────────────────────────────────────

st.subheader("Overview")
st.markdown("""
SIEVE annotates each extracted code snippet with `llm_score` — a probability
in [0, 1] indicating how likely the snippet is to be AI-generated rather than
human-written.

The classifier is a fine-tuned
[`microsoft/codebert-base`](https://huggingface.co/microsoft/codebert-base)
model with a linear classification head. It was trained on a labeled dataset
of 114,186 code snippets across four programming languages and nine LLMs.

Model weights are publicly available on HuggingFace:
[mrahman2025/sieve-llm-classifier](https://huggingface.co/mrahman2025/sieve-llm-classifier)
""")

st.divider()

# ── Architecture ──────────────────────────────────────────────────────────────

st.subheader("Architecture")
st.markdown("""
```
Code snippet (truncated to 512 tokens)
        ↓
CodeBERT encoder (microsoft/codebert-base, 125M params)
        ↓
[CLS] token embedding (768-dim)
        ↓
Dropout (p=0.1)
        ↓
Linear head (768 → 1)
        ↓
Sigmoid → llm_score ∈ [0, 1]
```

**Training details:**
- Loss: Binary Cross-Entropy with class weighting
- Optimizer: AdamW (lr=2e-5, weight decay=0.01)
- Effective batch size: 32 (gradient accumulation × 2)
- Warmup: 10% of total steps
- Early stopping: patience = 2 epochs on validation loss
- Best checkpoint: epoch 2 (val loss = 0.168)
""")

st.divider()

