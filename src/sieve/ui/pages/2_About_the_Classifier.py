# ── Limitations ───────────────────────────────────────────────────────────────

st.subheader("Limitations")
st.markdown("""
- **JavaScript classes** are underrepresented in training (838 human, 976 AI)
  due to the naturally function-heavy nature of the JS corpus.
- The classifier was trained on code generated by specific LLMs as of early 2026.
  Newer models with significantly different generation patterns may reduce accuracy.
- Very short snippets (< 5 tokens) may receive unreliable scores.
- The model processes at most 512 tokens — very long functions are truncated.
""")